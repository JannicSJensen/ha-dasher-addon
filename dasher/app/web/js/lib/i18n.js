/** Returns a translate function; unknown keys fall back to English, then to the key itself. */
export function makeTranslator(language = "en") {
  const dict = DICTIONARIES[String(language).toLowerCase().split("-")[0]] ?? DICTIONARIES.en;
  return (key) => dict[key] ?? DICTIONARIES.en[key] ?? key;
}

/** t() with {n} style placeholders. */
export function format(t, key, values = {}) {
  return Object.entries(values).reduce((text, [k, v]) => text.replaceAll(`{${k}}`, String(v)), t(key));
}

/** Translate an HA state or mode value, e.g. "heat_cool" -> "Heat/Cool". */
export function translateState(t, value) {
  if (value == null) return "";
  const key = String(value);
  const translated = t(key);
  if (translated !== key) return translated;
  const pretty = key.replace(/_/g, " ");
  return pretty.charAt(0).toUpperCase() + pretty.slice(1);
}
